using System.Reflection;
using System.Text.Json.Serialization;
using Elevant.Api.Configuration;
using Elevant.Api.Controllers;
using Elevant.Contracts.Integration;
using Elevant.Contracts.Operations;
using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Http.Metadata;
using Microsoft.AspNetCore.Mvc;
using Microsoft.AspNetCore.Mvc.ModelBinding;
using Microsoft.AspNetCore.Mvc.Routing;

namespace Elevant.ArchitectureTests.Architecture;

/// <summary>
/// ADR-0041: the demo flight contracts expose public identifiers only, accept no unknown member, stay under the
/// superadministrator's governance routes, and the demo mark of the OCC reads is optional and written only when set.
/// </summary>
public sealed class DemoFlightContractSafetyTests
{
    private static readonly Type[] DemoContracts = typeof(DemoFlightResponse).Assembly.GetTypes()
        .Where(type => type.Namespace == typeof(DemoFlightResponse).Namespace && type.Name.Contains("Demo", StringComparison.Ordinal))
        .ToArray();

    [Fact]
    public void DemoContractsExposeNoInternalKeys()
    {
        Assert.Superset(new HashSet<Type>
        {
            typeof(CreateDemoFlightRequest), typeof(CancelDemoFlightRequest), typeof(DemoFlightResponse),
            typeof(DemoFlightListResponse), typeof(DemoFlightOptionsResponse), typeof(DemoStationOptionResponse),
            typeof(DemoAirlineOptionResponse), typeof(DemoAirportOptionResponse), typeof(DemoAircraftTypeOptionResponse),
            typeof(DemoStandOptionResponse), typeof(DemoFlightLimitsResponse), typeof(DemoFlightWarningResponse),
        }, DemoContracts.ToHashSet());
        var properties = DemoContracts.SelectMany(type => type.GetProperties(BindingFlags.Instance | BindingFlags.Public))
            .ToArray();

        Assert.DoesNotContain(properties, property =>
            property.PropertyType == typeof(long) || property.PropertyType == typeof(long?) ||
            (Nullable.GetUnderlyingType(property.PropertyType) ?? property.PropertyType).IsEnum ||
            property.Name.Contains("Password", StringComparison.OrdinalIgnoreCase) ||
            property.Name.Contains("Token", StringComparison.OrdinalIgnoreCase) ||
            property.Name.Contains("Email", StringComparison.OrdinalIgnoreCase));
        // Every identifier a screen receives or sends is a public UUID.
        Assert.All(properties.Where(property => property.Name == "Id" || property.Name.EndsWith("Id", StringComparison.Ordinal)),
            property => Assert.True(property.PropertyType == typeof(Guid) || property.PropertyType == typeof(Guid?),
                $"{property.DeclaringType!.Name}.{property.Name}"));
        // The flight numbers and the registration are generated by the server, never sent.
        Assert.DoesNotContain(typeof(CreateDemoFlightRequest).GetProperties(), property =>
            property.Name.Contains("FlightNumber", StringComparison.Ordinal) ||
            property.Name.Contains("Registration", StringComparison.Ordinal));
        // The cancel carries an intent, not the row version the progress worker makes stale by design.
        Assert.Equal(["Intent"], typeof(CancelDemoFlightRequest).GetProperties().Select(property => property.Name));
    }

    [Fact]
    public void DemoWriteContractsRejectUnknownJsonMembers()
    {
        foreach (var type in new[] { typeof(CreateDemoFlightRequest), typeof(CancelDemoFlightRequest) })
        {
            var attribute = Assert.Single(type.GetCustomAttributes<JsonUnmappedMemberHandlingAttribute>(inherit: false));
            Assert.Equal(JsonUnmappedMemberHandling.Disallow, attribute.UnmappedMemberHandling);
        }
    }

    [Fact]
    public void DemoRoutesStayUnderGovernance()
    {
        var controller = typeof(DemoFlightsController);
        var route = Assert.Single(controller.GetCustomAttributes<RouteAttribute>(inherit: false));
        Assert.Equal("api/v{version:apiVersion}/governance", route.Template);
        Assert.Single(controller.GetCustomAttributes<AuthorizeAttribute>(inherit: false));
        Assert.Single(controller.GetCustomAttributes<PrivateResponseAttribute>(inherit: false));
        Assert.Empty(controller.GetCustomAttributes<AllowAnonymousAttribute>(inherit: true));

        var actions = controller.GetMethods(BindingFlags.Instance | BindingFlags.Public | BindingFlags.DeclaredOnly)
            .Select(method => (Method: method, Http: method.GetCustomAttribute<HttpMethodAttribute>()))
            .Where(item => item.Http is not null)
            .ToArray();
        // The operationIds the snapshot publishes, their verbs and their routes under governance.
        Assert.Equal(
            [
                "CancelDemoFlight POST demo-flights/{demoFlightId:guid}/cancel",
                "CreateDemoFlight POST demo-flights",
                "GetDemoFlightOptions GET demo-flights/options",
                "ListDemoFlights GET demo-flights",
            ],
            actions.Select(item => $"{item.Http!.Name} {Assert.Single(item.Http.HttpMethods)} {item.Http.Template}")
                .Order(StringComparer.Ordinal));
        Assert.All(actions.Where(item => item.Http!.HttpMethods.Contains("POST")).Select(item => item.Method), command =>
        {
            var limit = command.GetCustomAttribute<RequestSizeLimitAttribute>() as IRequestSizeLimitMetadata;
            Assert.Equal((long?)2048, limit?.MaxRequestBodySize);
            var key = Assert.Single(command.GetParameters(), parameter =>
                parameter.GetCustomAttribute<FromHeaderAttribute>()?.Name == "Idempotency-Key");
            Assert.Equal(typeof(Guid), key.ParameterType);
            Assert.NotNull(key.GetCustomAttribute<BindRequiredAttribute>());
            // The account, the station scope and the authority come from the session, never from the request.
            Assert.DoesNotContain(command.GetParameters(), parameter =>
                parameter.Name is "accountId" or "actorId" or "organizationId");
        });
    }

    [Fact]
    public void TheDemoMarkIsOptionalAndWrittenOnlyWhenSet()
    {
        foreach (var type in new[] { typeof(OccFlightProposalResponse), typeof(OccTurnaroundResponse),
                     typeof(OccPositionTurnaroundResponse) })
        {
            var mark = type.GetProperty("IsDemo");
            Assert.NotNull(mark);
            Assert.Equal(typeof(bool?), mark.PropertyType);
            Assert.Equal(JsonIgnoreCondition.WhenWritingNull, mark.GetCustomAttribute<JsonIgnoreAttribute>()?.Condition);
            // The last parameter with a default: every caller that never heard of demo flights still compiles.
            var parameter = type.GetConstructors().Single().GetParameters()[^1];
            Assert.Equal(((string?)"IsDemo", true, (object?)null),
                (parameter.Name, parameter.HasDefaultValue, parameter.DefaultValue));
        }
    }

    [Fact]
    public void TheDemoWorkerDependsOnlyOnApplicationAbstractions()
    {
        var worker = typeof(DemoFlightsController).Assembly.GetType("Elevant.Api.Integration.DemoFlightProgressWorker");
        Assert.NotNull(worker);
        Assert.All(Assert.Single(worker.GetConstructors()).GetParameters(), parameter =>
            Assert.True(parameter.ParameterType.Namespace is { } name &&
                (name == "System" || name.StartsWith("Microsoft.Extensions.", StringComparison.Ordinal) ||
                 name.StartsWith("Elevant.Application.", StringComparison.Ordinal)),
                $"{parameter.Name}: {parameter.ParameterType.FullName}"));
    }
}
