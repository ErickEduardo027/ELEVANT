#!/usr/bin/env node
// Generates the offline airline registry used when Wikidata does not answer (ADR-0023) from
// OpenFlights `airlines.dat` (ODbL 1.0, https://openflights.org/data). Pass the path of the file
// downloaded from the pinned commit below; its SHA-256 is checked so the output is reproducible.
// Run with --check to fail when the committed TSV is stale.
//
//   curl -sSfL -o airlines.dat \
//     https://raw.githubusercontent.com/jpatokal/openflights/5d623a6969a1adee7961cf1c9a8a212c4a784713/data/airlines.dat
//   node scripts/data/generate-openflights-airlines.mjs airlines.dat
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = 'backend/Elevant.Infrastructure/Integrations/AirlineRegistry/openflights-airlines.tsv';
const SOURCE_SHA256 = '39be1a432e8b04ebc12860c29281c974a9cb52169c82b2456a835d66ab1548a1';

const args = process.argv.slice(2);
const check = args.includes('--check');
const input = args.find(arg => !arg.startsWith('--'));
if (!input) {
  console.error('Usage: generate-openflights-airlines.mjs <airlines.dat> [--check]');
  process.exit(2);
}

const raw = readFileSync(input);
const digest = createHash('sha256').update(raw).digest('hex');
if (digest !== SOURCE_SHA256) {
  console.error(`Unexpected airlines.dat (sha256 ${digest}); download it from the pinned commit.`);
  process.exit(1);
}

// airlines.dat is CSV with quoted fields and \N for nulls.
function parse(line) {
  const fields = [];
  let current = '';
  let quoted = false;
  for (let index = 0; index < line.length; index++) {
    const char = line[index];
    if (quoted) {
      if (char === '"' && line[index + 1] === '"') { current += '"'; index++; }
      else if (char === '"') quoted = false;
      else current += char;
    } else if (char === '"') quoted = true;
    else if (char === ',') { fields.push(current); current = ''; }
    else current += char;
  }
  fields.push(current);
  return fields.map(field => (field === '\\N' ? '' : field.trim()));
}

const clean = value => value.replace(/[\t\r\n]/g, ' ').trim();
const rows = raw.toString('utf8').split(/\r?\n/).filter(Boolean).map(parse)
  .map(([, name, , iata, icao, , country, active]) => ({
    name: clean(name ?? ''), iata: (iata ?? '').toUpperCase(), icao: (icao ?? '').toUpperCase(),
    country: clean(country ?? ''), active: active === 'Y' ? 'Y' : 'N',
  }))
  .filter(row => row.name && (/^[A-Z0-9]{2}$/.test(row.iata) || /^[A-Z]{3}$/.test(row.icao)))
  .map(row => ({ ...row, iata: /^[A-Z0-9]{2}$/.test(row.iata) ? row.iata : '', icao: /^[A-Z]{3}$/.test(row.icao) ? row.icao : '' }))
  .sort((a, b) => a.icao.localeCompare(b.icao) || a.iata.localeCompare(b.iata) || a.name.localeCompare(b.name));

const output = [
  '# OpenFlights airlines (ODbL 1.0, https://openflights.org/data), commit 5d623a6969a1adee7961cf1c9a8a212c4a784713.',
  '# Generated by scripts/data/generate-openflights-airlines.mjs; do not edit by hand.',
  'name\tiata\ticao\tcountry\tactive',
  ...rows.map(row => [row.name, row.iata, row.icao, row.country, row.active].join('\t')),
  '',
].join('\n');

const target = resolve(root, OUT);
if (check) {
  let current = '';
  try { current = readFileSync(target, 'utf8'); } catch { /* missing counts as stale */ }
  if (current !== output) {
    console.error(`${OUT} is stale; run the generator.`);
    process.exit(1);
  }
  console.log(`${OUT} is up to date (${rows.length} airlines).`);
} else {
  writeFileSync(target, output);
  console.log(`Wrote ${OUT} (${rows.length} airlines).`);
}
