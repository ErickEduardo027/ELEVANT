// Builds the OCC legacy bridge stylesheet from its manifest (occLegacyBridgeMap.js), and finds legacy colour classes in
// source text. Pure, without the file system: occStyleGuard.test.js runs it in memory, compares the result with the
// committed src/styles/occ-legacy-bridge.css, and rewrites that file when UPDATE_OCC_BRIDGE=1.
import { BREAKPOINTS } from '../config/breakpoints.js';
import { OCC_BRIDGE_DEFAULTS, OCC_BRIDGE_SCOPE, OCC_LEGACY_BRIDGE } from './occLegacyBridgeMap.js';

const STYLESHEET_HEADER = `/* Generated by src/styles/occLegacyBridge.js from src/styles/occLegacyBridgeMap.js: do not edit by hand.
   To change it, edit the manifest and run, in frontend/private-web:
   UPDATE_OCC_BRIDGE=1 npx vitest run --configLoader runner --config vitest.config.mjs src/styles/occStyleGuard.test.js

   The legacy bridge repaints the legacy utility classes of the screens mounted under /admin-occ with the dark tokens
   of occ.css. It applies only under ${OCC_BRIDGE_SCOPE}: AdminOccLayout sets data-occ-bridge on
   the shell, and removing that attribute switches the whole bridge off. Every class rule is worth at least two
   attributes and a class, so it beats the plain (one class) and dark: (two classes) utilities of Tailwind whatever the
   order; the defaults rule weighs nothing, so every colour class beats it. Only an entry of plain selectors may carry
   !important, the one way to beat an inline style. */`;

// Every element and pseudo-element inside the shell, at zero specificity, like Tailwind's own preflight.
const DEFAULT_TARGETS = ['*', '::before', '::after'];

// The variants the bridge knows and what each adds to the selector. `dark:` adds nothing: the OCC is dark only, so its
// dark classes are always the ones that count. A screen variant becomes a media query.
const STATE_VARIANTS = Object.freeze({
  dark: '',
  hover: ':hover',
  focus: ':focus',
  'focus-visible': ':focus-visible',
  'read-only': ':read-only',
  disabled: ':disabled',
  'aria-[current=true]': '[aria-current="true"]',
});

// Tailwind paints a divide colour on the children of the element, between siblings.
const DIVIDE_CHILDREN = ' > :not([hidden]) ~ :not([hidden])';

// A typo in a property name would silently do nothing in the browser, so the manifest may only use these.
const BRIDGE_PROPERTIES = new Set([
  'color', 'background-color', 'border-color', 'border-left-color', 'outline-color', 'accent-color', '--tw-ring-color',
  '--tw-shadow', '--tw-shadow-colored', 'backdrop-filter', '-webkit-backdrop-filter',
  'border-radius', 'border-top-left-radius', 'border-top-right-radius', 'font-family',
]);

const IDENTIFIER_CHARACTER = /[A-Za-z0-9_-]/;
const DIGIT = /[0-9]/;

// Splits `dark:hover:bg-white/5` into its variants and the utility, leaving the colons inside brackets alone.
function splitVariants(className) {
  const parts = [];
  let depth = 0;
  let start = 0;
  for (let index = 0; index < className.length; index += 1) {
    const character = className[index];
    if (character === '[') depth += 1;
    else if (character === ']') depth -= 1;
    else if (character === ':' && depth === 0) {
      parts.push(className.slice(start, index));
      start = index + 1;
    }
  }
  parts.push(className.slice(start));
  return { variants: parts.slice(0, -1), utility: parts.at(-1) };
}

// A class name as a CSS identifier: every character outside [A-Za-z0-9_-] is escaped with a backslash (`/`, `[`, `]`,
// `.`, `:`, `%`, `=`, …), and a leading digit is written as a hex escape, which is the only way to escape a digit.
function escapeClassName(className) {
  return [...className].map((character, index) => {
    const leadsIdentifier = index === 0 || (index === 1 && className[0] === '-');
    if (DIGIT.test(character) && leadsIdentifier) return `\\3${character} `;
    if (IDENTIFIER_CHARACTER.test(character) || character.codePointAt(0) >= 0x80) return character;
    return `\\${character}`;
  }).join('');
}

/**
 * The selector of one class, without the scope: the escaped class, the pseudo-classes of its state variants and, for
 * `divide-*`, the children it paints. A screen variant (`sm:` … `3xl:`) comes back as `media`. An unknown variant
 * throws, so a class the bridge cannot reproduce never reaches the stylesheet.
 */
export function bridgeSelector(className) {
  if (typeof className !== 'string' || className === '' || /\s/.test(className)) {
    throw new TypeError(`Not a class name: ${JSON.stringify(className)}`);
  }
  const { variants, utility } = splitVariants(className);
  if (utility === '') throw new TypeError(`Not a class name: ${JSON.stringify(className)}`);
  let state = '';
  let media = null;
  for (const variant of variants) {
    if (Object.hasOwn(BREAKPOINTS, variant)) {
      if (media !== null) throw new Error(`The OCC bridge takes one screen variant per class: ${className}`);
      media = `(min-width: ${BREAKPOINTS[variant]}px)`;
    } else if (Object.hasOwn(STATE_VARIANTS, variant)) {
      state += STATE_VARIANTS[variant];
    } else {
      throw new Error(`The OCC bridge does not know the variant "${variant}" of ${className}`);
    }
  }
  const children = utility.startsWith('divide-') ? DIVIDE_CHILDREN : '';
  return { selector: `.${escapeClassName(className)}${state}${children}`, media };
}

function plainSelector(className, role) {
  const { selector, media } = bridgeSelector(className);
  if (media !== null) throw new Error(`A class used in ${role} cannot have a screen variant: ${className}`);
  return selector;
}

function checkDeclarations(id, declarations) {
  const properties = Object.keys(declarations ?? {});
  if (properties.length === 0) throw new Error(`Bridge entry ${id} declares nothing`);
  for (const property of properties) {
    if (!BRIDGE_PROPERTIES.has(property)) throw new Error(`Bridge entry ${id} sets an unknown property: ${property}`);
    const value = declarations[property];
    // `!` too: the generator alone writes !important, and only for an important entry.
    if (typeof value !== 'string' || value.trim() === '' || /[;{}!]/.test(value)) {
      throw new Error(`Bridge entry ${id} has an invalid value for ${property}: ${JSON.stringify(value)}`);
    }
  }
}

const scoped = selector => `${OCC_BRIDGE_SCOPE} ${selector}`;

function formatRule(selectors, declarations, { indent = '', important = false } = {}) {
  const priority = important ? ' !important' : '';
  const body = Object.entries(declarations).map(([property, value]) => `${indent}  ${property}: ${value}${priority};`);
  return [selectors.map(selector => `${indent}${selector}`).join(',\n') + ' {', ...body, `${indent}}`].join('\n');
}

// !important beats an inline style, and nothing else may need it: an important entry names plain selectors (the
// elements that carry the inline style) and no class, so it can never outweigh the class rules of the bridge.
function checkImportant(entry) {
  if (entry.important === undefined || entry.important === false) return false;
  const plainOnly = entry.important === true && entry.classes.length === 0 && entry.selectors?.length > 0
    && !(entry.inside?.length > 0) && !(entry.pairs?.length > 0);
  if (!plainOnly) throw new Error(`Bridge entry ${entry.id} may be important only with plain selectors and no class`);
  return true;
}

// A plain selector of the manifest: one compound or complex selector, never a list or a block.
function checkSelector(id, selector) {
  if (typeof selector !== 'string' || selector.trim() === '' || /[{},;]|^\s*[>+~]/.test(selector)) {
    throw new Error(`Bridge entry ${id} has an invalid selector: ${JSON.stringify(selector)}`);
  }
  return selector.trim();
}

function entryRules(entry) {
  const important = checkImportant(entry);
  const rules = [];
  const plain = [];
  const byMedia = new Map();
  for (const className of entry.classes) {
    const { selector, media } = bridgeSelector(className);
    if (media === null) plain.push(scoped(selector));
    else byMedia.set(media, [...(byMedia.get(media) ?? []), scoped(selector)]);
  }
  for (const selector of entry.selectors ?? []) plain.push(scoped(checkSelector(entry.id, selector)));
  if (plain.length > 0) rules.push(formatRule(plain, entry.declarations, { important }));
  for (const [media, selectors] of byMedia) {
    rules.push(`@media ${media} {\n${formatRule(selectors, entry.declarations, { indent: '  ' })}\n}`);
  }

  if (entry.inside?.length > 0) {
    if (!Object.hasOwn(entry.declarations, 'color')) throw new Error(`Bridge entry ${entry.id} has inside classes but no color`);
    const selectors = entry.classes.flatMap(outer => entry.inside.map(inner =>
      scoped(`${plainSelector(outer, 'inside')} ${plainSelector(inner, 'inside')}`)));
    rules.push(formatRule(selectors, { color: entry.declarations.color }));
  }

  if (entry.pairs?.length > 0) {
    // The same element (`.a.b`) or a descendant (`.a .b`).
    const selectors = entry.pairs.flatMap(([outer, inner]) => {
      const [first, second] = [plainSelector(outer, 'pairs'), plainSelector(inner, 'pairs')];
      return [scoped(`${first}${second}`), scoped(`${first} ${second}`)];
    });
    rules.push(formatRule(selectors, entry.declarations));
  }
  return rules;
}

/**
 * The stylesheet of the bridge: the defaults rule, then one section per entry in the order of the manifest. Throws on
 * a malformed entry.
 */
export function generateOccLegacyBridgeCss(manifest = OCC_LEGACY_BRIDGE, { defaults = OCC_BRIDGE_DEFAULTS } = {}) {
  checkDeclarations('defaults', defaults);
  const defaultsSection = ['/* defaults */', formatRule(DEFAULT_TARGETS.map(target => `:where(${OCC_BRIDGE_SCOPE}) ${target}`), defaults)]
    .join('\n');
  const ids = new Set(['defaults']);
  const sections = manifest.map(entry => {
    if (typeof entry.id !== 'string' || !/^[a-z][a-z0-9-]*$/.test(entry.id)) {
      throw new Error(`Bridge entry id must be kebab-case: ${JSON.stringify(entry.id)}`);
    }
    if (ids.has(entry.id)) throw new Error(`Bridge entry id used twice: ${entry.id}`);
    ids.add(entry.id);
    checkDeclarations(entry.id, entry.declarations);
    if (!Array.isArray(entry.classes)
      || (entry.classes.length === 0 && !(entry.pairs?.length > 0) && !(entry.selectors?.length > 0))) {
      throw new Error(`Bridge entry ${entry.id} applies to no class`);
    }
    return [`/* ${entry.id} */`, ...entryRules(entry)].join('\n');
  });
  return `${[STYLESHEET_HEADER, defaultsSection, ...sections].join('\n\n')}\n`;
}

// Legacy colours: the palette of tailwind.config.js that the OCC tokens replace, white and black, and Tailwind's
// default palette. Also an occ colour with an opacity modifier, for which Tailwind generates no class at all.
const TAILWIND_HUES = 'slate|gray|zinc|neutral|stone|red|orange|amber|yellow|lime|green|emerald|teal|cyan|sky|blue|indigo'
  + '|violet|purple|fuchsia|pink|rose';
const LEGACY_COLOURS = [
  'ink-\\d{2,3}', 'accent-\\d{2,3}', 'signal-\\d{2,3}', 'surface-(?:light-card|dark-card|light|dark)',
  'text-(?:primary|secondary)-(?:light|dark)', 'status-(?:info|active|success|warning|danger|neutral)', 'white', 'black',
  `(?:${TAILWIND_HUES})-(?:50|[1-9]00|950)`,
].join('|');
const COLOUR_UTILITIES = '(?:text|bg|border(?:-[xytrblse])?|ring(?:-offset)?|divide|outline|from|via|to|placeholder|fill'
  + '|stroke|shadow|caret|decoration|accent)';
const VARIANT_PREFIX = '(?:[a-z0-9\\[\\]&>_.=-]+:)*';
const OPACITY = '\\/(?:\\d+|\\[[^\\]\\s]+\\])';
const LEGACY_COLOUR_CLASS = new RegExp(
  `(?<![\\w:/.\\[-])(${VARIANT_PREFIX}${COLOUR_UTILITIES}-(?:(?:${LEGACY_COLOURS})(?:${OPACITY})?|occ-[a-z]+(?:-[a-z]+)*${OPACITY}))`
    + '(?![\\w/\\[-])',
  'g',
);

/**
 * The legacy colour classes of a source text, each once, in order of appearance: plain, `dark:`, state variants,
 * arbitrary opacity (`bg-black/[.03]`), Tailwind's default palette, and occ colours with an opacity modifier. The
 * coverage guard and the MIGRATED_FOLDERS guard share this expression.
 */
export function findLegacyColourClasses(source) {
  return [...new Set([...source.matchAll(LEGACY_COLOUR_CLASS)].map(match => match[1]))];
}
