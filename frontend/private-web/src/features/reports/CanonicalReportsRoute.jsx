// Template D of the design («Registro»): the toolbar with the report, its period and its filters, then the generated
// page as a panel with its downloads in the header, its figures, the dense table with its totals and its pages.
const PAGE_SIZE = 25;
const SLAB = 'rounded-md border border-occ-line bg-occ-panel text-occ-text';
// From 1280 px the rows scroll inside the panel, under their sticky headers, and the page keeps the toolbar, the
// panel's header with the downloads and its pages on screen.
const ROWS_HEIGHT = 'xl:max-h-[calc(100dvh-24rem)]';
// The filters whose options come from another screen of the OCC, by catalog key.
const LOOKUP_FILTERS = new Set(['airline', 'agent', 'terminal']);
const FORMATS = Object.freeze([['pdf', 'downloadPdf'], ['xlsx', 'downloadExcel']]);
const NO_FILTERS = Object.freeze([]);

/**
 * The month so far in the station's calendar (3-N26): from 20:00 in Punta Cana the UTC day is already tomorrow, and
 * on the evening of the last day of the month the browser's UTC month would be the next one.
 */
export function defaultPeriod(now = new Date()) {
  return presetRange('thisMonth', businessToday(now));
}

/**
 * The options of each filter of the chosen report: its own list (status) or the one read for it into `lookups`
 * (`null` when the account cannot read it).
 */
function useFilterOptions(filters, stationId, today, lookups, setLookups) {
  const wanted = filters.filter(filter => LOOKUP_FILTERS.has(filter.key) && !filter.options?.length)
    .map(filter => filter.key).sort().join(',');
  useEffect(() => {
    if (!wanted || !stationId) return undefined;
    const controller = new AbortController();
    for (const kind of wanted.split(',')) {
      loadOccFilterOptions(kind, stationId, today, { signal: controller.signal })
        .then(options => { if (!controller.signal.aborted) setLookups(current => ({ ...current, [kind]: options })); })
        .catch(() => {});
    }
    return () => controller.abort();
  }, [wanted, stationId, today, setLookups]);
  return useMemo(() => filters.map(filter => ({ ...filter,
    choices: filter.options?.length ? filter.options.map(option => ({ value: option.code, label: option.label }))
      : lookups[filter.key] ?? null })), [filters, lookups]);
}

/**
 * OCC reports generated by the API (teacher review, Phase 5; ADR-0048): choose a report, a period (with its shortcuts)
 * and the report's own filters, read it page by page and download the whole period as PDF or Excel. The list of
 * reports and each page show their loading, failure and refusal under the toolbar; a refusal (403) offers no retry.
 */
export default function CanonicalReportsRoute() {
  const { t, locale } = useTranslation(reportsMessages);
  const station = useOccStation();
  const access = useOptionalDepartmentAccess();
  const canExport = access ? Boolean(access.can('operations.reports.export')) : true;
  const descriptionId = useId();
  const [today] = useState(() => businessToday());
  // The options read for the airline, agent and terminal filters, by filter key.
  const [lookups, setLookups] = useState({});
  const source = useMemo(() => createOccReportSource(station.stationCode), [station.stationCode]);
  const initialValues = useMemo(() => ({ stationId: station.stationId }), [station.stationId]);
  const report = useServerReport({
    source, initialKey: 'operations', today, initialValues, pageSize: PAGE_SIZE, enabled: Boolean(station.stationId),
    labels: { period: t('period'), asOf: t('asOf') },
    // «Filtros aplicados» names the chosen options until the server names them itself (ADR-0048).
    describe: (query, definition) => [
      { label: t('station'), value: station.stationCode, base: true },
      ...definition.filters.filter(filter => query[filter.parameter]).map(filter => ({ label: filter.label,
        value: filter.options?.find(option => option.code === query[filter.parameter])?.label
          ?? lookups[filter.key]?.find(option => option.value === query[filter.parameter])?.label
          ?? query[filter.parameter] })),
    ],
  });
  const { catalog, draft, selected, applied, setValue } = report;
  const filters = useFilterOptions(selected?.filters ?? NO_FILTERS, station.stationId, today, lookups, setLookups);
  useEffect(() => { if (station.stationId) setValue('stationId', station.stationId); }, [setValue, station.stationId]);

  // An English screen keeps the server's Spanish content and its own words around it.
  const presets = PERIOD_PRESETS.map(preset => ({ id: preset.id, label: t(`presets.${preset.id}`) }));
  const asOfDate = Boolean(selected?.asOfDate);
  const ready = catalog.status === 'success' && Boolean(selected);
  const validation = report.validation
    ? t(`validation.${report.validation}`, { days: catalog.maxRangeDays ?? '' }) : '';

  let result = null;
  if (catalog.status === 'error') {
    // The service's own sentence (occReportsService), never the server's title.
    result = <OccRemoteView status="error" className={SLAB} labels={{ error: catalog.error.message, retry: t('retry') }}
      onRetry={catalog.error.retryable ? report.retryCatalog : undefined} />;
  } else if (applied) {
    const state = report.report;
    const data = state.status === 'success' ? state.data : null;
    // While a page loads or fails, the panel keeps the name of the report asked for.
    const title = data?.title ?? applied.definition.title ?? t('title');
    const count = data ? rowsCountText({ rows: data.rows.length, totalRows: data.totalRows, page: data.page, paged: true },
      t('counts')) : '';
    const meta = data ? (
      <span className="flex flex-wrap gap-x-3 gap-y-0.5">
        {count ? <span>{count}</span> : null}
        <span>{formatGeneratedAt(data.asOf, { locale, by: data.generatedBy,
          template: data.generatedBy ? t('generatedBy') : t('generatedAt') })}</span>
      </span>
    ) : null;
    const empty = !data || data.rows.length === 0;
    const actions = data && canExport ? (
      <span role="group" aria-label={t('downloads')} className="flex flex-wrap gap-2">
        {FORMATS.map(([format, label]) => (
          <OccButton key={format} size="sm" busy={report.exporting === format} busyLabel={t('exporting')}
            disabled={Boolean(report.exporting) || empty} onClick={() => void report.exportAs(format)}>
            {t(label)}
          </OccButton>
        ))}
      </span>
    ) : null;
    const exportError = report.exportError;
    // 3-N13: a download is the whole period or nothing; a PDF over its 5 000 rows can still go to Excel.
    const exportMessage = !exportError ? '' : exportError.format === 'pdf' && exportError.code === 'report_too_large'
      ? t('pdfTooLarge') : t('exportFailed', { message: exportError.message });
    const columns = data ? data.columns.map((column, index) => ({
      key: String(index), header: column.label, align: isNumericType(column.type) ? 'end' : undefined,
      render: row => formatReportValue(row[index], column.type),
    })) : [];
    const totals = report.totals;
    const summary = filtersSummary(report.summary, { prefix: t('filtersApplied') });
    result = (
      <OccPanel title={title} meta={meta} actions={actions} status={state.status}
        labels={{ loading: t('loading'), retry: t('retry'), ...(report.failure ? { error: report.failure.message } : {}) }}
        onRetry={report.failure?.retryable ? report.retry : undefined}
        skeleton={<OccSkeleton rows={8} label={t('loading')} />}>
        {data ? (
          <>
            {summary ? <p className="border-b border-occ-line px-3 py-2 text-sm text-occ-muted">{summary}</p> : null}
            {exportMessage ? (
              <p role="alert" className="flex items-start gap-2 border-b border-occ-line bg-occ-warn-soft px-3 py-2 text-sm text-occ-text">
                <OccGlyph name="attention" className="mt-0.5" />
                <span className="min-w-0">{exportMessage}</span>
              </p>
            ) : null}
            {data.summary.length ? (
              <OccStatList label={t('summary')} className="grid grid-cols-2 gap-3 border-b border-occ-line px-3 py-3 md:grid-cols-4">
                {data.summary.map(metric => (
                  <OccStatTile key={metric.label} label={metric.label} value={metric.value} detail={metric.context ?? undefined} />
                ))}
              </OccStatList>
            ) : null}
            <OccDataTable caption={data.title} columns={columns} rows={data.rows} scrollClassName={ROWS_HEIGHT}
              emptyState={<OccEmptyState title={t('empty')} />}
              footer={totals ? (
                <dl aria-label={totals.label || t('totals')} className="flex flex-wrap gap-x-4 gap-y-1 text-sm">
                  <dt className="font-semibold">{totals.label || t('totals')}</dt>
                  {totals.cells.map((cell, index) => (index === 0 || cell === '' || !data.columns[index] ? null : (
                    <dd key={data.columns[index].label} className="tabular-nums">
                      <span className="text-occ-muted">{data.columns[index].label}: </span>
                      {formatReportValue(cell, data.columns[index].type)}
                    </dd>
                  )))}
                </dl>
              ) : undefined} />
            {data.page > 1 || data.hasMore ? (
              <nav aria-label={t('pages')} className="flex items-center justify-end gap-2 border-t border-occ-line px-3 py-2">
                <OccButton size="sm" disabled={data.page <= 1} onClick={() => report.turnPage(-1)}>{t('previous')}</OccButton>
                <OccButton size="sm" disabled={!data.hasMore} onClick={() => report.turnPage(1)}>{t('next')}</OccButton>
              </nav>
            ) : null}
          </>
        ) : null}
      </OccPanel>
    );
  } else if (catalog.status === 'loading') {
    // The list of reports is on its way, on the first visit and after «Reintentar»: its place says so, in the shape of
    // the two lines that follow it, while the «Reporte» list waits empty and disabled.
    result = <OccRemoteView status="loading" className={SLAB}
      skeleton={<OccSkeleton variant="text" rows={2} className="max-w-2xl" label={t('loadingCatalog')} />} />;
  } else if (catalog.status === 'success') {
    result = (
      <div className={`${SLAB} p-3`}>
        <OccEmptyState title={t('idleTitle')} description={t('idleDescription')} />
      </div>
    );
  }

  // The station is in the status bar of the OCC frame: the page has no badge of its own, nor a line under its title.
  // The chosen report's description sits under the toolbar and describes the «Reporte» list.
  return (
    <section className="flex min-w-0 flex-col gap-3 text-occ-text">
      <div className="flex min-w-0 flex-col gap-1.5">
        <OccToolbar title={t('title')} label={t('filters')}>
          {station.stationId ? (
            <form onSubmit={report.generate} noValidate className="flex min-w-0 flex-wrap items-end gap-2">
              <OccSelectField label={t('report')} className="w-72 max-w-full" value={draft.key} disabled={!ready}
                aria-describedby={selected ? descriptionId : undefined}
                onChange={event => report.setKey(event.target.value)}>
                {catalog.reports.map(item => <option key={item.key} value={item.key}>{item.title}</option>)}
              </OccSelectField>
              {!asOfDate ? (
                <OccSegmented label={t('period')} size="sm" options={presets} value={draft.preset}
                  onChange={report.setPreset} />
              ) : null}
              {!asOfDate ? (
                <OccTextField type="date" label={t('from')} className="w-40" value={draft.from} max={draft.to}
                  onChange={event => report.setDate('from', event.target.value)} />
              ) : null}
              <OccTextField type="date" label={asOfDate ? t('asOf') : t('to')} className="w-40" value={draft.to}
                min={asOfDate ? undefined : draft.from} onChange={event => report.setDate('to', event.target.value)} />
              {filters.filter(filter => filter.choices?.length).map(filter => (
                <OccSelectField key={filter.key} label={filter.label} className="w-52 max-w-full"
                  value={draft.values[filter.parameter] ?? ''}
                  onChange={event => setValue(filter.parameter, event.target.value)}>
                  <option value="">{t('all')}</option>
                  {filter.choices.map(choice => <option key={choice.value} value={choice.value}>{choice.label}</option>)}
                </OccSelectField>
              ))}
              <OccButton variant="primary" type="submit" disabled={!ready}>{t('generate')}</OccButton>
            </form>
          ) : null}
        </OccToolbar>
        {station.stationId && selected ? <p id={descriptionId} className="text-sm text-occ-muted">{selected.description}</p> : null}
        {validation ? <p role="alert" className="text-sm text-occ-text">{validation}</p> : null}
      </div>
      {station.stationId ? result : <p role="alert" className={`${OCC_CLASSES.card} text-sm`}>{t('noStation')}</p>}
    </section>
  );
}
