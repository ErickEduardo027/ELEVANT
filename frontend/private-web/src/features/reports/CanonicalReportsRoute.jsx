import { downloadOccReport, getOccReport, listOccReports } from '../../services/occReportsService';
import { reportsMessages } from './reportsMessages';

// Template D of the design («Registro»): the toolbar with the report and its period, then the generated page as a
// panel with its export actions in the header, the dense table and the pages at its foot.
const PAGE_SIZE = 25;
const FORMATS = [{ id: 'xlsx', label: 'Excel' }, { id: 'pdf', label: 'PDF' }, { id: 'csv', label: 'CSV' }];
const SLAB = 'rounded-md border border-occ-line bg-occ-panel text-occ-text';
// From 1280 px the rows scroll inside the panel, under their sticky headers, and the page keeps the toolbar, the
// panel's header with the exports and its pages on screen: 19.5 rem is the status bar, the page's padding, the toolbar
// with the description, the panel's header and its pages.
const ROWS_HEIGHT = 'xl:max-h-[calc(100dvh-19.5rem)]';

/**
 * The month so far in the station's calendar (3-N26): from 20:00 in Punta Cana the UTC day is already tomorrow, and
 * on the evening of the last day of the month the browser's UTC month would be the next one.
 */
export function defaultPeriod(now = new Date()) {
  const to = businessToday(now);
  return { from: `${to.slice(0, 8)}01`, to };
}

/**
 * The columns of a report page: the server's headers in its order, with nothing added. A column that holds numbers
 * sits on the right with tabular figures, and so do its «—» placeholders. No column sorts: the server pages the
 * report, so an order on screen would only cover the page.
 */
function reportColumns(data) {
  return data.columns.map((header, index) => ({
    key: String(index),
    header,
    align: data.rows.some(row => row[index]?.type === 'number') ? 'end' : undefined,
    render: row => row[index]?.value,
  }));
}

/**
 * OCC reports generated by the API (teacher review, Phase 5): choose a report and a period, read it page by page and
 * export the whole period to Excel, PDF or CSV. A refusal (403) offers no retry.
 */
export default function CanonicalReportsRoute() {
  const { t, locale } = useTranslation(reportsMessages);
  const station = useOccStation();
  const access = useOptionalDepartmentAccess();
  const canExport = access ? Boolean(access.can('operations.reports.export')) : true;
  const descriptionId = useId();
  const [catalog, setCatalog] = useState({ status: 'loading', reports: [] });
  const [catalogAttempt, setCatalogAttempt] = useState(0);
  const [filters, setFilters] = useState(() => ({ key: 'operations', ...defaultPeriod() }));
  const [query, setQuery] = useState(null);
  const [page, setPage] = useState(1);
  const [report, setReport] = useState({ status: 'idle' });
  const [exporting, setExporting] = useState('');
  const [exportError, setExportError] = useState('');

  useEffect(() => {
    const controller = new AbortController();
    listOccReports({ signal: controller.signal })
      .then(result => setCatalog({ status: 'success', reports: result.reports }))
      .catch(error => { if (error?.name !== 'AbortError') setCatalog({ status: 'error', reports: [], error }); });
    return () => controller.abort();
  }, [catalogAttempt]);

  useEffect(() => {
    if (!query || !station.stationId) return undefined;
    const controller = new AbortController();
    getOccReport(query.key, { stationId: station.stationId, from: query.from, to: query.to, page, limit: PAGE_SIZE },
      { signal: controller.signal })
      .then(data => setReport({ status: 'success', data }))
      .catch(error => { if (error?.name !== 'AbortError') setReport({ status: 'error', error }); });
    return () => controller.abort();
  }, [query, page, station.stationId]);

  const generate = useCallback(event => {
    event.preventDefault();
    setExportError('');
    setPage(1);
    setReport({ status: 'loading' });
    setQuery({ ...filters });
  }, [filters]);

  async function exportAs(format) {
    setExporting(format);
    setExportError('');
    try {
      await downloadOccReport(query.key, { stationId: station.stationId, from: query.from, to: query.to }, format, station.stationCode);
    } catch (error) {
      // 3-N13: an export is the whole period or nothing; a PDF over its 5 000 rows can still go to Excel or CSV.
      setExportError(format === 'pdf' && error?.code === 'report_too_large'
        ? t('pdfTooLarge') : t('exportFailed', { message: error.message }));
    } finally {
      setExporting('');
    }
  }

  const turnPage = step => { setReport({ status: 'loading' }); setPage(value => value + step); };
  const retry = () => { setReport({ status: 'loading' }); setQuery(current => ({ ...current })); };
  const retryCatalog = () => { setCatalog({ status: 'loading', reports: [] }); setCatalogAttempt(value => value + 1); };

  const selected = catalog.reports.find(item => item.key === filters.key);
  const data = report.status === 'success' ? report.data : null;

  let result = null;
  if (catalog.status === 'error') {
    // The service's own sentence (occReportsService), never the server's title.
    result = <OccRemoteView status="error" className={SLAB} labels={{ error: catalog.error.message, retry: t('retry') }}
      onRetry={catalog.error.status !== 403 ? retryCatalog : undefined} />;
  } else if (query) {
    const failed = report.status === 'error';
    // While a page loads or fails, the panel keeps the name of the report asked for.
    const title = data?.title ?? catalog.reports.find(item => item.key === query.key)?.title ?? t('title');
    // A page without rows says so in its body; its header keeps only when it was generated.
    let rowsText = null;
    if (data?.rows.length === 1) rowsText = t('rowsOne', { page: data.page });
    else if (data?.rows.length > 0) rowsText = t('rows', { page: data.page, count: data.rows.length });
    const meta = data ? (
      <span className="flex flex-wrap gap-x-3 gap-y-0.5">
        {rowsText ? <span>{rowsText}</span> : null}
        <span>{t('generatedAt', { date: formatBusinessDateTime(data.asOf, { locale }) })}</span>
      </span>
    ) : null;
    const actions = data && canExport ? FORMATS.map(format => (
      <OccButton key={format.id} size="sm" busy={exporting === format.id} busyLabel={t('exporting')}
        disabled={Boolean(exporting) || data.rows.length === 0} onClick={() => void exportAs(format.id)}>
        {t('exportAs', { format: format.label })}
      </OccButton>
    )) : null;
    result = (
      <OccPanel title={title} meta={meta} actions={actions} status={report.status}
        labels={{ loading: t('loading'), retry: t('retry'), ...(failed ? { error: report.error.message } : {}) }}
        onRetry={failed && report.error.status !== 403 ? retry : undefined}
        skeleton={<OccSkeleton rows={8} label={t('loading')} />}>
        {data ? (
          <>
            {exportError ? (
              <p role="alert" className="flex items-start gap-2 border-b border-occ-line bg-occ-warn-soft px-3 py-2 text-sm text-occ-text">
                <OccGlyph name="attention" className="mt-0.5" />
                <span className="min-w-0">{exportError}</span>
              </p>
            ) : null}
            <OccDataTable caption={data.title} columns={reportColumns(data)} rows={data.rows} scrollClassName={ROWS_HEIGHT}
              emptyState={<OccEmptyState title={t('empty')} />} />
            {data.page > 1 || data.hasMore ? (
              <nav aria-label={t('pages')} className="flex items-center justify-end gap-2 border-t border-occ-line px-3 py-2">
                <OccButton size="sm" disabled={data.page <= 1} onClick={() => turnPage(-1)}>{t('previous')}</OccButton>
                <OccButton size="sm" disabled={!data.hasMore} onClick={() => turnPage(1)}>{t('next')}</OccButton>
              </nav>
            ) : null}
          </>
        ) : null}
      </OccPanel>
    );
  } else if (catalog.status === 'success') {
    result = (
      <div className={`${SLAB} p-3`}>
        <OccEmptyState title={t('idleTitle')} description={t('idleDescription')} />
      </div>
    );
  }

  // The station is in the status bar of the OCC frame: the page has no badge of its own, nor a line under its title.
  // The chosen report's description sits under the toolbar and describes the «Reporte» list.
  return (
    <section className="flex min-w-0 flex-col gap-3 text-occ-text">
      <div className="flex min-w-0 flex-col gap-1.5">
        <OccToolbar title={t('title')} label={t('filters')}>
          {station.stationId ? (
            <form onSubmit={generate} noValidate className="flex min-w-0 flex-wrap items-end gap-2">
              <OccSelectField label={t('report')} className="w-72 max-w-full" value={filters.key}
                disabled={catalog.status !== 'success'} aria-describedby={selected ? descriptionId : undefined}
                onChange={event => setFilters(current => ({ ...current, key: event.target.value }))}>
                {catalog.reports.map(item => <option key={item.key} value={item.key}>{item.title}</option>)}
              </OccSelectField>
              <OccTextField type="date" label={t('from')} className="w-44" value={filters.from} max={filters.to}
                onChange={event => setFilters(current => ({ ...current, from: event.target.value }))} />
              <OccTextField type="date" label={t('to')} className="w-44" value={filters.to} min={filters.from}
                onChange={event => setFilters(current => ({ ...current, to: event.target.value }))} />
              <OccButton variant="primary" type="submit"
                disabled={catalog.status !== 'success' || !filters.from || !filters.to}>
                {t('generate')}
              </OccButton>
            </form>
          ) : null}
        </OccToolbar>
        {station.stationId && selected ? <p id={descriptionId} className="text-sm text-occ-muted">{selected.description}</p> : null}
      </div>
      {station.stationId ? result : <p role="alert" className={`${OCC_CLASSES.card} text-sm`}>{t('noStation')}</p>}
    </section>
  );
}
