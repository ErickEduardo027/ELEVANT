function asDate(value: Date | string | number): Date {
  const date = value instanceof Date ? new Date(value) : new Date(value);
  if (!Number.isFinite(date.getTime())) {
    throw new TypeError("El reloj del portal debe producir una fecha válida.");
  }
  return date;
}

function shift(reference: Date, milliseconds: number): string {
  return new Date(reference.getTime() + milliseconds).toISOString();
}

function day(reference: Date, offset = 0): string {
  const value = new Date(reference);
  value.setUTCDate(value.getUTCDate() + offset);
  return value.toISOString().slice(0, 10);
}

function provenance(
  reference: Date,
  sourceRecordId: string,
  offsetMinutes = -5,
): DataProvenance {
  return {
    source: "ELEVANT_CORE",
    sourceRecordId,
    capturedAt: shift(reference, offsetMinutes * 60_000),
    lastSyncedAt: shift(reference, -2 * 60_000),
    quality: "VERIFIED",
  };
}

